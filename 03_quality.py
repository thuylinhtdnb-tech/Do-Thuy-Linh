"""Phan 2a: bao cao chat luong du lieu tu dong -> reports/dq_report.md

Chay:  python src\03_quality.py
Can:   data/curated/financials_zstd.parquet, failures.parquet, institutions.parquet (tu 02_storage.py)
"""
import sys
from pathlib import Path

import polars as pl

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config as C

CUR = C.DATA / "curated"
FIG = C.REPORTS / "figures"
FIG.mkdir(parents=True, exist_ok=True)
OUT = C.REPORTS / "dq_report.md"
md = []


def h(t, lvl=2):
    md.append(f"\n{'#' * lvl} {t}\n")


def p(t):
    md.append(t + "\n")


PLAIN_COLS = ("year", "first_year_<50%_null")  # cot nam: khong dung dau phay ngan cach


def fmt(x, plain=False):
    if x is None:
        return ""
    if isinstance(x, float):
        return f"{x:,.3f}"
    if isinstance(x, int):
        return str(x) if plain else f"{x:,}"
    return str(x)


def table(df, n=40):
    d = df.head(n)
    lines = ["| " + " | ".join(d.columns) + " |", "|" + "---|" * len(d.columns)]
    for r in d.rows():
        lines.append("| " + " | ".join(fmt(x, c in PLAIN_COLS) for x, c in zip(r, d.columns)) + " |")
    md.append("\n".join(lines) + "\n")


def parse_date(col):
    return pl.coalesce([
        pl.col(col).cast(pl.Utf8).str.to_date(f, strict=False)
        for f in ("%m/%d/%Y", "%Y-%m-%d", "%Y%m%d", "%Y/%m/%d")
    ])


def main():
    fin = pl.read_parquet(CUR / "financials_zstd.parquet")
    failures = pl.read_parquet(CUR / "failures.parquet")
    inst = pl.read_parquet(CUR / "institutions.parquet")

    print("failures columns:", failures.columns)
    print("institutions columns (", len(inst.columns), "):", inst.columns[:40], "...")

    p("# Data Quality Report (auto-generated by src/03_quality.py)")

    # ------------------------------------------------------------ 1. Overview
    h("1. Overview and schema")
    expected = set(C.FIN_FIELDS)
    extra = sorted(set(fin.columns) - expected)
    missing = sorted(expected - set(fin.columns))
    p(f"- Rows: **{fin.height:,}**; columns: **{fin.width}**; distinct banks (CERT): **{fin['CERT'].n_unique():,}**; "
      f"quarters: **{fin['REPDTE'].n_unique()}** ({fin['REPDTE'].min()} to {fin['REPDTE'].max()})")
    p(f"- Columns returned but not requested in config: {extra or 'none'}; requested but absent: {missing or 'none'}")
    key_dups = fin.height - fin.select(["CERT", "REPDTE"]).unique().height
    p(f"- Duplicate (CERT, REPDTE) keys: **{key_dups}**")

    fin = fin.with_columns(
        pl.col("REPDTE").dt.year().cast(pl.Int32).alias("year"),
        (pl.col("REPDTE").dt.year().cast(pl.Int32) * 4
         + (pl.col("REPDTE").dt.month().cast(pl.Int32) - 1) // 3).alias("qidx"),
    )
    value_cols = [c for c in fin.columns if c not in ("CERT", "REPDTE", "year", "qidx")]

    # ------------------------------------------------------------ 2. Missingness
    h("2. Missing values by field and year")
    nulls = (fin.group_by("year")
             .agg([pl.col(c).null_count().alias(c) for c in value_cols] + [pl.len().alias("_n")])
             .sort("year"))
    years = nulls["year"].to_list()
    rates = nulls.select([(pl.col(c) / pl.col("_n")).alias(c) for c in value_cols]).to_numpy()
    rows = []
    for j, c in enumerate(value_cols):
        first = next((y for y, r in zip(years, rates[:, j]) if r < 0.5), None)
        rows.append({"field": c, "null_rate_overall": fin[c].null_count() / fin.height,
                     "first_year_<50%_null": first})
    table(pl.DataFrame(rows).sort("null_rate_overall", descending=True))
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(11, 6))
        im = ax.imshow(rates.T, aspect="auto", vmin=0, vmax=1, cmap="viridis_r")
        ax.set_yticks(range(len(value_cols)))
        ax.set_yticklabels(value_cols, fontsize=7)
        step = max(1, len(years) // 15)
        ax.set_xticks(range(0, len(years), step))
        ax.set_xticklabels(years[::step], rotation=45, fontsize=7)
        ax.set_title("Null rate by field and year")
        fig.colorbar(im, ax=ax, label="null rate")
        fig.tight_layout()
        fig.savefig(FIG / "null_heatmap.png", dpi=200)
        plt.close(fig)
        p("Figure: `reports/figures/null_heatmap.png`")
    except ImportError:
        p("(matplotlib not installed - heatmap skipped)")

    # ------------------------------------------------------------ 3. Rules
    h("3. Range / logic violations (flagged, not silently dropped)")
    rules = {
        "ASSET <= 0": (["ASSET"], pl.col("ASSET") <= 0),
        "ASSET is null": (["ASSET"], pl.col("ASSET").is_null()),
        "DEP < 0": (["DEP"], pl.col("DEP") < 0),
        "DEP > ASSET": (["DEP", "ASSET"], pl.col("DEP") > pl.col("ASSET")),
        "EQ < 0 (negative equity)": (["EQ"], pl.col("EQ") < 0),
        "EQ > ASSET": (["EQ", "ASSET"], pl.col("EQ") > pl.col("ASSET")),
        "LNLSNET > ASSET": (["LNLSNET", "ASSET"], pl.col("LNLSNET") > pl.col("ASSET")),
        "NCLNLS < 0": (["NCLNLS"], pl.col("NCLNLS") < 0),
        "LNATRES < 0": (["LNATRES"], pl.col("LNATRES") < 0),
        "abs(ROA) > 50 (percent)": (["ROA"], pl.col("ROA").abs() > 50),
        "NUMEMP < 0": (["NUMEMP"], pl.col("NUMEMP") < 0),
    }
    out = []
    for name, (cols, e) in rules.items():
        if not all(c in fin.columns for c in cols):
            continue
        sub = fin.filter(e.fill_null(False))
        out.append({"rule": name, "rows": sub.height, "pct_rows": 100 * sub.height / fin.height,
                    "banks": sub["CERT"].n_unique()})
    table(pl.DataFrame(out))

    h("Distribution of key fields (units: USD thousands; ratios in percent)", 3)
    qs = [0.001, 0.01, 0.5, 0.99, 0.999]
    rows = []
    for c in ["ASSET", "DEP", "EQ", "NETINC", "ROA", "NCLNLS", "LNATRES", "RBC1AAJ", "NIMY"]:
        if c in fin.columns:
            s = fin[c].drop_nulls()
            r = {"field": c, "min": s.min()}
            r.update({f"p{q * 100:g}": s.quantile(q) for q in qs})
            r["max"] = s.max()
            rows.append(r)
    table(pl.DataFrame(rows))

    # ------------------------------------------------------------ 4. Gaps and exits
    h("4. Panel structure: gaps and exits")
    last_q = fin["qidx"].max()
    per = (fin.group_by("CERT")
           .agg(pl.col("qidx").min().alias("first_q"), pl.col("qidx").max().alias("last_q"),
                pl.len().alias("n_q"), pl.col("REPDTE").max().alias("last_rep"),
                pl.col("REPDTE").min().alias("first_rep"))
           .with_columns((pl.col("last_q") - pl.col("first_q") + 1 - pl.col("n_q")).alias("gap_q")))
    g = per.filter(pl.col("gap_q") > 0)
    p(f"- Banks with at least one missing quarter between first and last report: **{g.height:,}** "
      f"(missing bank-quarters: {int(g['gap_q'].sum() or 0):,})")
    p(f"- Banks observed in only one quarter: **{per.filter(pl.col('n_q') == 1).height:,}**")
    exited = per.filter(pl.col("last_q") < last_q)
    p(f"- Banks whose last report is before {fin['REPDTE'].max()} (exited the sample): **{exited.height:,}** "
      f"of {per.height:,}")

    # ------------------------------------------------------------ 5. Failures
    h("5. Failures table and join integrity")
    p(f"Failures columns: `{failures.columns}`")
    f2 = failures.with_columns(pl.col("CERT").cast(pl.Int32, strict=False),
                               parse_date("FAILDATE").alias("fail_date"))
    unparsed = f2.filter(pl.col("fail_date").is_null()).height
    p(f"- Rows: {f2.height:,}; unparsable FAILDATE: {unparsed}; null CERT: {f2['CERT'].null_count()}")
    p(f"- FAILDATE range: {f2['fail_date'].min()} to {f2['fail_date'].max()}")
    if "COST" in f2.columns:
        cost = f2.with_columns(pl.col("COST").cast(pl.Float64, strict=False))
        p(f"- COST non-null: {cost.height - cost['COST'].null_count():,} of {cost.height:,}; "
          f"median {cost['COST'].median()}; mean {cost['COST'].mean()} (USD thousands)")
    in_scope = f2.filter(pl.col("fail_date") >= fin["REPDTE"].min())
    p(f"- Failures on/after {fin['REPDTE'].min()}: **{in_scope.height:,}**")
    j = in_scope.join(per.select(["CERT", "last_rep"]), on="CERT", how="left")
    no_fin = j.filter(pl.col("last_rep").is_null()).height
    p(f"- In-scope failures with **no** financial records: **{no_fin}**")
    jj = j.filter(pl.col("last_rep").is_not_null()).with_columns(
        (pl.col("fail_date") - pl.col("last_rep")).dt.total_days().alias("lag_days"))
    if jj.height:
        qv = [jj["lag_days"].quantile(q) for q in (0.05, 0.5, 0.95)]
        p(f"- Days from last Call Report to FAILDATE: p5={qv[0]}, median={qv[1]}, p95={qv[2]}")
        p(f"- Banks reporting **after** their FAILDATE (suspicious): {jj.filter(pl.col('lag_days') < 0).height}")
    yearly = (f2.filter(pl.col("fail_date").is_not_null())
              .group_by(pl.col("fail_date").dt.year().alias("year")).len().sort("year")
              .filter(pl.col("year") >= 1984))
    table(yearly.rename({"len": "failures"}), n=50)

    # ------------------------------------------------------------ 6. Exit classification preview
    h("6. Exit classification preview (failure vs other exits)")
    failed_certs = set(in_scope["CERT"].drop_nulls().to_list())
    ex = exited.with_columns(pl.col("CERT").is_in(list(failed_certs)).alias("is_failure"))
    p(f"- Exited banks that appear in Failures: **{ex.filter(pl.col('is_failure')).height:,}**; "
      f"other exits (merger, voluntary closure, charter change...): **{ex.filter(~pl.col('is_failure')).height:,}**")
    p(f"Institutions has {len(inst.columns)} columns. NOTE: ACTIVE / CHANGEC1 are *current-day* attributes and "
      "contain future information, so they are used only to classify exits, never as features.")
    inst2 = inst.with_columns(pl.col("CERT").cast(pl.Int32, strict=False))
    other = ex.filter(~pl.col("is_failure")).select("CERT")
    for col in ("ACTIVE", "CHANGEC1"):
        if col in inst2.columns:
            h(f"Institutions.{col} among non-failure exits", 3)
            t = (other.join(inst2.select(["CERT", col]), on="CERT", how="left")
                 .group_by(col).len().sort("len", descending=True))
            table(t.rename({"len": "banks"}), n=25)

    h("7. Issues found and handling policy")
    table(pl.DataFrame({
        "issue": ["Field not reported in early years (null)", "Logical violations (e.g. DEP > ASSET)",
                  "Negative equity", "Gaps in a bank's quarterly series", "Exit without failure",
                  "Failure with no Call Report", "Reports after FAILDATE", "Extreme ratios"],
        "handling": ["Keep null + missing-indicator; impute inside the train-only pipeline",
                     "Flag columns; exclude from ratios only if ASSET <= 0",
                     "Keep: it is a genuine distress signal", "Keep rows; lag features computed by calendar quarter, not row order",
                     "Label 0; last quarters flagged as censored/excluded (see 04_build_panel)",
                     "Cannot be modelled (no features); counted and reported", "Drop rows after FAILDATE",
                     "Winsorize inside the train-only pipeline"],
    }))

    OUT.write_text("\n".join(md), encoding="utf-8")
    print(f"Done -> {OUT}")


if __name__ == "__main__":
    main()
